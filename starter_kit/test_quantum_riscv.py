def qasm(body: str, qubits: int) -> str:
    return f'''OPENQASM 2.0;
include "qelib1.inc";
qreg q[{qubits}];
creg c[{qubits}];
{body}
'''


class QuantumRISCVE2ETests(unittest.TestCase):
    def test_all_twelve_gates_match_fixed_machine_words(self):
        # These literals are independent anchors derived from the encoding table
        # in QUANTUM_RISCV_SPEC.md, not values generated by the implementation.
        cases = [
            ("h", (3,), None, 0x0200018B),
            ("x", (4,), None, 0x0400020B),
            ("s", (5,), None, 0x0600028B),
            ("sdg", (6,), None, 0x0800030B),
            ("t", (7,), None, 0x0A00038B),
            ("tdg", (8,), None, 0x0C00040B),
            ("ry", (6,), math.pi / 2, 0x2000130B),
            ("rz", (7,), -math.pi / 2, 0xE000238B),
            ("cx", (1, 8), None, 0x0E00840B),
            ("cu1", (2, 9), math.pi / 2, 0x2001348B),
            ("swap", (3, 10), None, 0x1001850B),
            ("ccx", (4, 5, 11), None, 0x1252058B),
        ]
        for name, qubits, angle, expected_word in cases:
            with self.subTest(name=name):
                self.assertEqual(
                    encode_quantum_instruction(name, qubits, angle), expected_word
                )
                decoded = decode_quantum_instruction(expected_word)
                self.assertEqual((decoded.name, decoded.qubits), (name, qubits))
                if angle is not None:
                    self.assertLessEqual(abs(decoded.parameter - angle), ANGLE_SCALE / 2)

    def test_literal_bell_words_from_spec_bypass_encoder(self):
        # This is the four-line example in QUANTUM_RISCV_SPEC.md. Loading the
        # literals directly prevents an encoder bug from being hidden by decode.
        bell_words = [0x0200000B, 0x0E00008B, 0x1400050B, 0x1400858B]
        outcomes = set()
        for seed in range(128):
            emulator = TinyRISCVEmulator(seed)
            emulator.load_machine_program(bell_words, qubit_count=2)
            registers = emulator.execute()
            self.assertEqual(registers.get("x10", 0), registers.get("x11", 0))
            outcomes.add(registers.get("x10", 0))
        self.assertEqual(outcomes, {0, 1})

    def test_shared_ir_encodes_every_word_with_custom_opcode(self):
        circuit = parse_qasm(
            qasm(
                """h q[0]; x q[1]; s q[2]; sdg q[0]; t q[1]; tdg q[2];
                ry(pi/7) q[0]; rz(-pi/5) q[1]; cx q[0],q[1];
                cu1(pi/3) q[1],q[2]; swap q[0],q[2]; ccx q[0],q[1],q[2];
                measure q -> c;""",
                3,
            )
        )
        words = encode_quantum_circuit(circuit)

        self.assertEqual(len(words), 15)
        self.assertTrue(all(word & 0x7F == QUANTUM_OPCODE for word in words))
        self.assertEqual(
            [decode_quantum_instruction(word).name for word in words],
            [
                "h",
                "x",
                "s",
                "sdg",
                "t",
                "tdg",
                "ry",
                "rz",
                "cx",
                "cu1",
                "swap",
                "ccx",
                "measure",
                "measure",
                "measure",
            ],
        )
        emulator = TinyRISCVEmulator(seed=7)
        emulator.load_machine_program(words[:12], circuit.qubit_count)
        emulator.execute()
        overlap = sum(
            expected.conjugate() * actual
            for expected, actual in zip(simulate(circuit), emulator.quantum_state)
        )
        self.assertGreater(abs(overlap) ** 2, 0.99999)
        self.assertEqual(sum(run_quantum_circuit(circuit, 64, seed=7).values()), 64)

    def test_bell_and_ghz_execute_from_generated_machine_words(self):
        bell = parse_qasm(qasm("h q[0]; cx q[0],q[1]; measure q -> c;", 2))
        ghz = parse_qasm(
            qasm(
                "h q[0]; cx q[0],q[1]; cx q[1],q[2]; measure q -> c;", 3
            )
        )

        bell_counts = run_quantum_circuit(bell, 1024, seed=2026)
        ghz_counts = run_quantum_circuit(ghz, 1024, seed=2026)

        self.assertEqual(set(bell_counts), {"00", "11"})
        self.assertEqual(set(ghz_counts), {"000", "111"})
        self.assertGreater(bell_counts["00"], 400)
        self.assertGreater(bell_counts["11"], 400)
        self.assertGreater(ghz_counts["000"], 400)
        self.assertGreater(ghz_counts["111"], 400)

    def test_fixed_seed_hundred_circuit_statevector_differential(self):
        rng = random.Random(240826)
        gate_names = tuple(GATES)
        coverage = set()

        for case_index in range(100):
            forced_gate = gate_names[case_index] if case_index < len(gate_names) else None
            minimum_qubits = GATES[forced_gate][0] if forced_gate else 1
            qubit_count = rng.randint(minimum_qubits, 5)
            depth = rng.randint(1, 50)
            operations = []

            for operation_index in range(depth):
                available = [
                    name for name in gate_names if GATES[name][0] <= qubit_count
                ]
                name = (
                    forced_gate
                    if operation_index == 0 and forced_gate
                    else rng.choice(available)
                )
                arity, parameterized = GATES[name]
                qubits = tuple(rng.sample(range(qubit_count), arity))
                parameter = (
                    repr(rng.uniform(-100 * math.pi, 100 * math.pi))
                    if parameterized
                    else None
                )
                operations.append(Operation(name, qubits, parameter))
                coverage.add(name)

            circuit = Circuit(qubit_count, qubit_count, tuple(operations), ())
            emulator = TinyRISCVEmulator(seed=case_index)
            emulator.load_machine_program(
                encode_quantum_circuit(circuit), circuit.qubit_count
            )
            emulator.execute()
            reference = simulate(circuit)
            overlap = sum(
                expected.conjugate() * actual
                for expected, actual in zip(reference, emulator.quantum_state)
            )
            self.assertGreater(
                abs(overlap) ** 2,
                0.9999,
                f"fixed random differential case {case_index}",
            )

        self.assertEqual(coverage, set(GATES))

    def test_quantum_words_mix_with_classical_riscv(self):
        program = """
        qh q0
        qcx q0, q1
        qmeasure q0, x10
        qmeasure q1, x11
        add x12, x10, x11
        """
        outcomes = set()
        for seed in range(32):
            emulator = TinyRISCVEmulator(seed)
            emulator.load_program(program, qubit_count=2)
            state = emulator.execute()
            self.assertEqual(state.get("x10", 0), state.get("x11", 0))
            self.assertEqual(state.get("x12", 0), 2 * state.get("x10", 0))
            outcomes.add(state.get("x10", 0))
        self.assertEqual(outcomes, {0, 1})

    def test_parameter_mnemonic_accepts_readable_angle_expression(self):
        emulator = TinyRISCVEmulator(seed=7)
        emulator.load_program("qry q0, pi / 2\nqmeasure q0, x10", qubit_count=1)
        self.assertIn(emulator.execute().get("x10", 0), (0, 1))

    def test_measurement_collapses_before_second_read(self):
        program = """
        qh q0
        qmeasure q0, x10
        qmeasure q0, x11
        """
        for seed in range(32):
            emulator = TinyRISCVEmulator(seed)
            emulator.load_program(program, qubit_count=1)
            state = emulator.execute()
            self.assertEqual(state.get("x10", 0), state.get("x11", 0))

    def test_rejects_non_custom_reserved_and_malformed_words(self):
        with self.assertRaisesRegex(ValueError, "不是 LoomQ"):
            decode_quantum_instruction(0x00000013)  # Standard RISC-V ADDI.
        with self.assertRaisesRegex(ValueError, "保留的量子 funct3"):
            decode_quantum_instruction((0x4 << 12) | QUANTUM_OPCODE)
        malformed_h = encode_quantum_instruction("h", (0,)) | (1 << 15)
        with self.assertRaisesRegex(ValueError, "保留字段"):
            decode_quantum_instruction(malformed_h)
        with self.assertRaisesRegex(ValueError, "不能重复"):
            encode_quantum_instruction("cx", (1, 1))
        with self.assertRaisesRegex(ValueError, "有限角度"):
            encode_quantum_instruction("ry", (0,), math.inf)

    def test_enforces_documented_reliable_angle_range(self):
        for name in ("ry", "rz"):
            circuit = Circuit(
                1,
                1,
                (Operation(name, (0,), repr(MAX_ABS_ANGLE)),),
                (),
            )
            emulator = TinyRISCVEmulator()
            emulator.load_machine_program(encode_quantum_circuit(circuit), 1)
            emulator.execute()
            overlap = sum(
                expected.conjugate() * actual
                for expected, actual in zip(simulate(circuit), emulator.quantum_state)
            )
            self.assertGreater(abs(overlap) ** 2, 0.9999)

        for angle in (MAX_ABS_ANGLE + 1, 1e16, -1e16, 1e20):
            with self.subTest(angle=angle):
                with self.assertRaisesRegex(ValueError, "角度绝对值"):
                    encode_quantum_instruction("rz", (0,), angle)


